function transliterateRuToLat(input: string): string {
  const map: Record<string, string> = {
    а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i", й: "y",
    к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f",
    х: "kh", ц: "ts", ч: "ch", ш: "sh", щ: "shch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
  };
  return input
    .toLowerCase()
    .split("")
    .map((ch) => map[ch] ?? ch)
    .join("");
}

export function slugify(city: string): string {
  return transliterateRuToLat(city)
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

export function cityRouteSlug(city: string): string {
  return slugify(city);
}

export function cityNameFromSlug(slug: string): string | null {
  return rawCities.find((city) => cityRouteSlug(city) === slug) ?? null;
}

/**
 * Склонение городов для использования в предлогах "в", "для", "из"
 */
export function getCityDeclension(city: string) {
  // Родительный падеж (из кого? чего? - для "из Александрова", "для Александрова")
  let genitive = city;
  // Предложный падеж (о ком? о чем? - для "в Александрове")
  let prepositional = city;

  const lowerCity = city.toLowerCase();

  // Специфические исключения и сложные случаи (сначала проверяем их)
  if (lowerCity === "санкт-петербург") {
    genitive = "Санкт-Петербурга";
    prepositional = "Санкт-Петербурге";
  } else if (lowerCity === "ростов-на-дону") {
    genitive = "Ростова-на-Дону";
    prepositional = "Ростове-на-Дону";
  } else if (lowerCity === "нижний новгород") {
    genitive = "Нижнего Новгорода";
    prepositional = "Нижнем Новгороде";
  } else if (lowerCity === "великий новгород") {
    genitive = "Великого Новгорода";
    prepositional = "Великом Новгороде";
  } else if (lowerCity === "набережные челны") {
    genitive = "Набережных Челнов";
    prepositional = "Набережных Челнах";
  } else if (lowerCity === "минеральные воды") {
    genitive = "Минеральных Вод";
    prepositional = "Минеральных Водах";
  } else if (lowerCity === "великие луки") {
    genitive = "Великих Лук";
    prepositional = "Великих Луках";
  } else if (lowerCity === "йошкар-ола") {
    genitive = "Йошкар-Олы";
    prepositional = "Йошкар-Оле";
  } else if (lowerCity === "улан-удэ") {
    genitive = "Улан-Удэ";
    prepositional = "Улан-Удэ";
  } else if (lowerCity === "сочи" || lowerCity === "тольятти") {
    genitive = city;
    prepositional = city;
  } else if (lowerCity === "грозный") {
    genitive = "Грозного";
    prepositional = "Грозном";
  } else if (lowerCity === "нижний тагил") {
    genitive = "Нижнего Тагила";
    prepositional = "Нижнем Тагиле";
  } else if (lowerCity.includes("-на-")) {
    // Комсомольск-на-Амуре -> Комсомольска-на-Амуре
    const parts = city.split("-");
    const firstPart = parts[0];
    const { genitive: g1, prepositional: p1 } = getCityDeclension(firstPart);
    genitive = g1 + "-" + parts.slice(1).join("-");
    prepositional = p1 + "-" + parts.slice(1).join("-");
  } else if (lowerCity.includes(" ")) {
    // Сложные города с пробелом (Старый Оскол, Сергиев Посад)
    const parts = city.split(" ");
    if (parts.length === 2) {
      const first = parts[0].toLowerCase();
      
      // Если первое слово - прилагательное (Старый, Новый, Сергиев, Южно-)
      if (first.endsWith("ый") || first.endsWith("ий") || first.endsWith("ое") || first.endsWith("ая") || first.endsWith("ев") || first.endsWith("ов")) {
         // Склоняем оба
         const { genitive: g1, prepositional: p1 } = getCityDeclension(parts[0]);
         const { genitive: g2, prepositional: p2 } = getCityDeclension(parts[1]);
         genitive = g1 + " " + g2;
         prepositional = p1 + " " + p2;
      } else {
         // Склоняем только второе (например, Набережные Челны уже в исключениях, 
         // но если будет что-то еще)
         const { genitive: g2, prepositional: p2 } = getCityDeclension(parts[1]);
         genitive = parts[0] + " " + g2;
         prepositional = parts[0] + " " + p2;
      }
    }
  } else if (city.endsWith("ый") || city.endsWith("ий") || city.endsWith("ое")) {
    // Прилагательные города (Грозный, Долгопрудный, Яровое)
    if (city.endsWith("ое")) {
      genitive = city.slice(0, -2) + "ого";
      prepositional = city.slice(0, -2) + "ом";
    } else {
      genitive = city.slice(0, -2) + "ого";
      prepositional = city.slice(0, -2) + "ом";
    }
  } else if (city.endsWith("о") || city.endsWith("е")) {
    // Города на -о и -е (Подмосковье, Видное) часто не склоняются в разговорной речи, 
    // но по правилам: в Видном, из Видного. Оставим несклоняемыми для безопасности, если это не общеизвестные исключения.
  } else if (city.endsWith("и") || city.endsWith("ы")) {
    // Множественные (Химки, Мытищи)
    if (city === "Химки") {
      genitive = "Химок";
      prepositional = "Химках";
    } else if (city === "Мытищи") {
      genitive = "Мытищ";
      prepositional = "Мытищах";
    } else if (city === "Чебоксары") {
      genitive = "Чебоксар";
      prepositional = "Чебоксарах";
    } else if (city === "Шахты") {
      genitive = "Шахт";
      prepositional = "Шахтах";
    } else if (city === "Луховицы") {
      genitive = "Луховиц";
      prepositional = "Луховицах";
    } else if (city === "Озёры") {
      genitive = "Озёр";
      prepositional = "Озёрах";
    } else if (city === "Электроугли") {
      genitive = "Электроуглей";
      prepositional = "Электроуглях";
    } else if (city === "Кимры") {
      genitive = "Кимр";
      prepositional = "Кимрах";
    }
  } else if (city.endsWith("а")) {
    // Москва -> Москвы, Москве
    genitive = city.slice(0, -1) + (["г", "к", "х", "ж", "ч", "ш", "щ"].includes(city.slice(-2, -1).toLowerCase()) ? "и" : "ы");
    prepositional = city.slice(0, -1) + "е";
  } else if (city.endsWith("я")) {
    genitive = city.slice(0, -1) + "и";
    prepositional = city.slice(0, -1) + "е";
  } else if (city.endsWith("ь")) {
    genitive = city.slice(0, -1) + "и";
    prepositional = city.slice(0, -1) + "и";
  } else if ("бвгджзклмнпрстфхцчшщ".includes(city.slice(-1).toLowerCase())) {
    // Согласный (Александров, Новосибирск)
    genitive = city + "а";
    prepositional = city + "е";
  }

  return { genitive, prepositional };
}

export function getCityCardDescription(city: string): string {
  const { genitive, prepositional } = getCityDeclension(city);
  const templates = [
    `Финансовая консультация для клиентов из ${genitive}: личный план, структура капитала и стратегия роста.`,
    `Управление капиталом для жителей ${genitive}: инвестиции, риск-профиль и регулярный контроль портфеля.`,
    `Индивидуальные решения по финансам для ${genitive}: от целей до практического инвестиционного плана.`,
    `Консультации по инвестициям в ${prepositional}: системный подход, дисциплина и долгосрочная доходность.`,
  ];
  return templates[city.length % templates.length];
}
